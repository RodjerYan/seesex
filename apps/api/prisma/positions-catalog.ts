/** Все категории каталога. */
export const POSITION_CATEGORIES: readonly string[] = Object.keys(BASE_NAMES);

/** Минимум записей, требуемых спекой. */
export const MIN_SYSTEM_POSITIONS = 400;

/**
 * Строит полный список системных позиций.
 * Каждое базовое имя комбинируется с вариантами => имя уникально внутри категории.
 */
export function buildSystemPositions(): SystemPositionSeed[] {
  const result: SystemPositionSeed[] = [];
  const seen = new Set<string>();

  for (const [category, bases] of Object.entries(BASE_NAMES)) {
    for (const base of bases) {
      for (const variant of VARIANTS) {
        const name = `${base}${variant}`;
        const key = `${category}::${name}`;
        if (seen.has(key)) {
          throw new Error(`Дубликат позиции в seed: ${key}`);
        }
        seen.add(key);
        result.push({ name, category, iconName: null });
      }
    }
  }

  return result;
}

/** Считает и проверяет, что каталог >= MIN_SYSTEM_POSITIONS. */
export function countSystemPositions(): number {
  const positions = buildSystemPositions();
  if (positions.length < MIN_SYSTEM_POSITIONS) {
    throw new Error(
      `Seed-каталог позиций слишком мал: ${positions.length} < ${MIN_SYSTEM_POSITIONS}`,
    );
  }
  return positions.length;
}
